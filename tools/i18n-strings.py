#!/usr/bin/env python3
"""Interface translations: one table for Spanish and French, and a Korean table keyed by the English text.

  python tools/i18n-strings.py          # write i18n-es.js, i18n-fr.js and i18n-ko.js
  python tools/i18n-strings.py --check  # fail if they are out of date (run by the tests)

EXACT: an English interface string (as rendered, whitespace-normalised) -> (es, fr).
PATTERNS: an English sentence with {slots} -> (es, fr). Slots capture data values, which stay
as published unless the value is itself an EXACT entry. Only interface text is translated;
source evidence keeps its original language (HANDOFF binding constraint).
Korean (tools/i18n_table_ko.py: KO_EXACT and KO_PATTERNS, English -> Korean): a string without a Korean entry
stays in English; Korean entries whose English is no longer in i18n_table.py are left out.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from i18n_table import EXACT, PATTERNS, TITLES  # noqa: E402
from i18n_table_ko import KO_EXACT, KO_PATTERNS, KO_TITLE  # noqa: E402


def render(lang, index):
    if lang == "ko":
        exact = {en: KO_EXACT[en] for en, *_ in EXACT if en in KO_EXACT}
        patterns = [[en, KO_PATTERNS[en]] for en, *_ in PATTERNS if en in KO_PATTERNS]
        title, table = KO_TITLE, "tools/i18n_table_ko.py"
    else:
        exact = {en: tr[index] for en, *tr in EXACT}
        patterns = [[en, tr[index]] for en, *tr in PATTERNS]
        title, table = TITLES[lang], "tools/i18n_table.py"
    body = json.dumps({"title": title, "exact": exact, "patterns": patterns}, ensure_ascii=False, indent=1)
    return (f"// Generated by tools/i18n-strings.py from {table}: edit the table, not this file.\n"
            f"window.I18N_DICTS = window.I18N_DICTS || {{}};\nwindow.I18N_DICTS.{lang} = {body};\n")


def main():
    check = "--check" in sys.argv
    english = [en for en, *_ in EXACT]
    duplicates = sorted({en for en in english if english.count(en) > 1})
    if duplicates:
        raise SystemExit(f"duplicate English keys: {duplicates[:5]}")
    stale = []
    for lang, index in (("es", 0), ("fr", 1), ("ko", None)):
        path = ROOT / f"i18n-{lang}.js"
        text = render(lang, index)
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(path.name)
        else:
            path.write_text(text, encoding="utf-8")
    if stale:
        raise SystemExit(f"out of date, run python tools/i18n-strings.py: {', '.join(stale)}")
    missing = sum(en not in KO_EXACT for en, *_ in EXACT) + sum(en not in KO_PATTERNS for en, *_ in PATTERNS)
    print(f"{len(EXACT)} exact strings and {len(PATTERNS)} patterns, Spanish and French; Korean missing {missing}")


if __name__ == "__main__":
    main()
